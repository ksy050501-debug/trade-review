// 무역 탐정단 — 문제·채점 검증 (node tests/verify.js)
const L = require('../js/logic.js');
const cfg = L.clone(L.DEFAULT_CONFIG);
let fails = 0; const out = [];
const check = (n, c, d) => { out.push(`${c ? 'PASS' : 'FAIL'}  ${n}${d ? ' — ' + d : ''}`); if (!c) fails++; };
const right2 = { trade: 'd1', export: 'd2', import: 'd3' };
const right3 = Object.fromEntries(L.S3.cards.map((c) => [c.id, c.answer]));
const right4 = Object.fromEntries(L.S4.items.map((i) => [i.id, { place: i.place, dir: i.dir }]));
check('만점 = 150점 (낱말 30 + 분류 50 + 지도 70)', L.MAX_SCORE === 150, String(L.MAX_SCORE));
check('분류 카드: 수출 5장·수입 5장', L.S3.cards.filter((c) => c.answer === 'ex').length === 5);
check('지도 물건마다 정답 나라가 서로 다름', new Set(L.S4.items.map((i) => i.place)).size === L.S4.items.length);
check('지도 정답 나라가 모두 지도에 있음', L.S4.items.every((i) => L.placeById(i.place)));
const s = L.createState(cfg);
check('입장 단계에서는 제출 불가', !L.submit(s, 'gaon', 's2', right2).ok);
L.setStage(s, cfg, 2);
check('뜻을 다 고르지 않으면 제출 불가', !L.submit(s, 'gaon', 's2', { trade: 'd1' }).ok);
let r = L.submit(s, 'gaon', 's2', { trade: 'd1', export: 'd3', import: 'd2' });
check('처음 제출: 1개 맞음 → 10점', r.ok && r.points === 10 && L.status(s, 'gaon', 's2') === 'fix');
r = L.submit(s, 'gaon', 's2', right2);
check('고쳐서 다시 내면 해결되지만 점수는 처음 답으로 (10점 유지)', r.ok && L.status(s, 'gaon', 's2') === 'done' && L.score(s, 'gaon').per.s2 === 10);
L.submit(s, 'narae', 's2', right2);
check('한 번에 다 맞히면 30점', L.score(s, 'narae').per.s2 === 30);
check('다음 사건 문제는 지금 제출 불가', !L.submit(s, 'gaon', 's3', right3).ok);
L.setStage(s, cfg, 3);
const wrong3 = Object.assign({}, right3, { c1: 'ex', c2: 'im' });
L.submit(s, 'gaon', 's3', wrong3);
check('분류 8장 맞음 → 40점', L.score(s, 'gaon').per.s3 === 40);
L.submit(s, 'narae', 's3', right3);
L.setStage(s, cfg, 4);
check('지도: 한국을 정답 나라로 고를 수 없음', !L.submit(s, 'gaon', 's4', Object.assign({}, right4, { car: { place: 'kr', dir: 'ex' } })).ok);
const w4 = L.clone(right4); w4.car.dir = 'im'; w4.chip.place = 'us';
L.submit(s, 'gaon', 's4', w4);
check('지도: 방향 1개·나라 1개 틀림 → 60점', L.score(s, 'gaon').per.s4 === 60);
L.submit(s, 'narae', 's4', right4);
check('나래국 만점 150', L.score(s, 'narae').total === 150);
check('가온국 10+40+60 = 110', L.score(s, 'gaon').total === 110);
const rk = L.ranking(s, cfg);
check('순위: 나래국 1위, 가온국 2위, 아직 0점인 두 나라는 공동 3위', rk[0].id === 'narae' && rk[1].id === 'gaon' && rk[2].rank === 3 && rk[3].rank === 3, JSON.stringify(rk.map((x) => x.name + x.rank)));
L.setStage(s, cfg, 5);
check('추측 없이 궁금증 제출 불가', !L.submitCurious(s, 'gaon', { card: 'f1', guess: ' ' }).ok);
check('궁금증 제출', L.submitCurious(s, 'gaon', { card: 'f2', guess: '외국 차가 더 좋아서?', question: '왜 둘 다 할까?' }).ok && L.status(s, 'gaon', 's5') === 'done');
check('궁금증 단계는 점수에 영향 없음', L.score(s, 'gaon').total === 110);
check('200자 넘으면 제출 불가', !L.submitCurious(s, 'daon', { card: 'f1', guess: 'ㄱ'.repeat(201) }).ok);
out.push(`\n결과: ${fails ? fails + '개 실패' : '모든 검증 통과'}`);
console.log(out.join('\n')); process.exit(fails ? 1 : 0);
